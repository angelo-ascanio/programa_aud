import { escapeHtml } from './html';
import {
  extractClausePlaceholders,
  sanitizeClauseHtml,
  stripHtmlToSearchText,
} from './clauseRenderer';

export type RichTextEditorLang = 'es' | 'en';
export type RichTextEditorMode = 'visual' | 'html' | 'preview';
export type RichTextWrapTag = 'strong' | 'em' | 'u';

export interface InsertTextAtCursorResult {
  value: string;
  nextCursor: number;
}

export type SafeLinkValidationResult =
  | { valid: true; href: string }
  | { valid: false; error: string };

export interface EditorLanguageStatus {
  hasContent: boolean;
  label: 'Con contenido' | 'Vacío';
  hasTitle: boolean;
}

export interface BilingualEditorDraftLike {
  title_es: string;
  content_html_es: string;
  title_en: string;
  content_html_en: string;
}

export interface BilingualDraftContentStatus {
  es: EditorLanguageStatus;
  en: EditorLanguageStatus;
}

function clampOffset(offset: number, length: number): number {
  if (!Number.isFinite(offset)) return 0;
  const intOffset = Math.trunc(offset);
  if (intOffset < 0) return 0;
  if (intOffset > length) return length;
  return intOffset;
}

/**
 * Deterministic string manipulation helper for HTML source mode:
 * wraps the `[start, end]` character range with `<tag>...</tag>`.
 */
export function wrapSelectionWithTag(
  html: string,
  start: number,
  end: number,
  tag: RichTextWrapTag
): string {
  const source = html ?? '';
  const rawStart = clampOffset(start, source.length);
  const rawEnd = clampOffset(end, source.length);
  const selStart = Math.min(rawStart, rawEnd);
  const selEnd = Math.max(rawStart, rawEnd);

  const before = source.slice(0, selStart);
  const selected = source.slice(selStart, selEnd);
  const after = source.slice(selEnd);

  return `${before}<${tag}>${selected}</${tag}>${after}`;
}

/**
 * Inserts `{clause_...}` placeholder tokens or HTML snippets at exact cursor/selection bounds
 * and returns the updated source string together with the exact resulting caret index.
 */
export function insertTextAtCursor(
  source: string,
  cursorStart: number,
  cursorEnd: number,
  insertion: string
): InsertTextAtCursorResult {
  const base = source ?? '';
  const textToInsert = insertion ?? '';
  const rawStart = clampOffset(cursorStart, base.length);
  const rawEnd = clampOffset(cursorEnd, base.length);
  const selStart = Math.min(rawStart, rawEnd);
  const selEnd = Math.max(rawStart, rawEnd);

  const value = `${base.slice(0, selStart)}${textToInsert}${base.slice(selEnd)}`;
  return {
    value,
    nextCursor: selStart + textToInsert.length,
  };
}

/**
 * Normalizes raw `contenteditable` or source HTML into clean, semantic, XSS-safe HTML:
 * - Converts `<b>` → `<strong>` and `<i>` → `<em>`.
 * - Cleans `contenteditable` trailing `<br>` and empty placeholder `<div>`/`<p>` artifacts.
 * - Executes `sanitizeClauseHtml()` allowlist filtering before saving or rendering.
 */
export function normalizeEditorHtmlOutput(rawHtml: string): string {
  if (!rawHtml || !rawHtml.trim()) {
    return '';
  }

  let working = rawHtml.replace(/\r\n?/g, '\n');

  // Map legacy bold/italic tags to semantic HTML5 equivalents
  working = working
    .replace(/<b(?=\s|>|\/)/gi, '<strong')
    .replace(/<\/b\s*>/gi, '</strong>')
    .replace(/<i(?=\s|>|\/)/gi, '<em')
    .replace(/<\/i\s*>/gi, '</em>');

  // Run allowlist sanitization early so stray style/script/class attributes cannot interfere
  working = sanitizeClauseHtml(working);

  // Strip trailing <br> inserted by browsers at the end of <p> or <div> blocks
  working = working.replace(/(<br>\s*)+(<\/(?:p|div|li)>)/gi, '$2');

  // Remove completely empty <p> / <div> artifact blocks generated by Enter/Backspace in contenteditable
  working = working
    .replace(/<(p|div)>\s*(?:<br>|&nbsp;|\u00a0)?\s*<\/\1>/gi, '')
    .replace(/^(?:\s*<br>\s*)+|(?:\s*<br>\s*)+$/gi, '');

  // Collapse redundant nested identical <div><div>...</div></div> or <p><p>...</p></p> wrappers
  let prev = '';
  while (working !== prev) {
    prev = working;
    working = working
      .replace(/<div>\s*(<div>[\s\S]*?<\/div>)\s*<\/div>/gi, '$1')
      .replace(/<p>\s*(<p>[\s\S]*?<\/p>)\s*<\/p>/gi, '$1');
  }

  const normalized = sanitizeClauseHtml(working).trim();
  if (!normalized) {
    return '';
  }

  // If no visible text, no {clause_...} token, and no structural table remains, treat as empty
  const hasVisibleText = stripHtmlToSearchText(normalized).length > 0;
  const hasTokens = extractClausePlaceholders(normalized).length > 0;
  const hasTable = /<table\b/i.test(normalized);
  if (!hasVisibleText && !hasTokens && !hasTable) {
    return '';
  }

  return normalized;
}

/**
 * Generates a clean ISO normative note HTML block (`<div><strong>NOTA:</strong> ...</div>`).
 */
export function buildIsoNoteHtmlSnippet(
  label: 'NOTA' | 'NOTE' = 'NOTA',
  placeholder?: string
): string {
  const cleanLabel = label === 'NOTE' ? 'NOTE' : 'NOTA';
  const defaultBody =
    cleanLabel === 'NOTE'
      ? 'Text of the normative note.'
      : 'Texto de la nota normativa.';
  const body = (placeholder ?? defaultBody).trim() || defaultBody;
  return `<div><strong>${cleanLabel}:</strong> ${escapeHtml(body)}</div>`;
}

/**
 * Generates a clean normative table HTML snippet with `<thead>`, `<tbody>`, `<th>`, and `<td>`.
 * Defaults to 2 total rows (1 header row + 1 data row) and 2 columns.
 */
export function buildSimpleTableHtmlSnippet(rows = 2, cols = 2): string {
  const safeRows = Math.max(1, Math.min(20, Math.trunc(Number.isFinite(rows) ? rows : 2)));
  const safeCols = Math.max(1, Math.min(10, Math.trunc(Number.isFinite(cols) ? cols : 2)));

  const headerCells: string[] = [];
  for (let c = 1; c <= safeCols; c += 1) {
    headerCells.push(`<th>Columna ${c}</th>`);
  }

  const dataRowCount = Math.max(1, safeRows - 1);
  const bodyRows: string[] = [];
  for (let r = 1; r <= dataRowCount; r += 1) {
    const cells: string[] = [];
    for (let c = 1; c <= safeCols; c += 1) {
      cells.push(`<td>Dato ${r}.${c}</td>`);
    }
    bodyRows.push(`<tr>${cells.join('')}</tr>`);
  }

  return `<table><thead><tr>${headerCells.join('')}</tr></thead><tbody>${bodyRows.join('')}</tbody></table>`;
}

/**
 * Validates that an author-entered link URL strictly matches `^https?:\/\/`
 * (blocking `javascript:`, `data:`, and relative/empty values without `window.prompt`).
 */
export function validateSafeHttpUrl(rawUrl: string): SafeLinkValidationResult {
  const trimmed = (rawUrl || '').replace(/[\u0000-\u001f\u007f]/g, '').trim();
  if (!trimmed) {
    return {
      valid: false,
      error: 'Ingresa una URL válida que comience con https:// o http://.',
    };
  }
  if (!/^https?:\/\/[^\s"'<>]+$/i.test(trimmed)) {
    return {
      valid: false,
      error: 'Solo se permiten enlaces seguros con protocolo https:// o http://.',
    };
  }
  return {
    valid: true,
    href: trimmed,
  };
}

/**
 * Builds a sanitized `<a href="...">` snippet after validating `^https?:\/\/`.
 * Throws if the URL fails safe protocol validation.
 */
export function buildSafeAnchorHtmlSnippet(rawUrl: string, linkText?: string): string {
  const validation = validateSafeHttpUrl(rawUrl);
  if (!validation.valid) {
    throw new Error(validation.error);
  }
  const label = (linkText || '').trim() || validation.href;
  return sanitizeClauseHtml(
    `<a href="${escapeHtml(validation.href)}">${escapeHtml(label)}</a>`
  );
}

/**
 * Determines whether a clause's HTML buffer contains meaningful authored content
 * (visible text, `{clause_...}` placeholder tokens, or a `<table>`).
 */
export function hasEditorHtmlContent(rawHtml: string): boolean {
  return normalizeEditorHtmlOutput(rawHtml).length > 0;
}

/**
 * Computes bilingual completion status badges (`Con contenido` vs `Vacío`) for ES and EN tabs.
 */
export function computeBilingualDraftStatus(
  draft: BilingualEditorDraftLike
): BilingualDraftContentStatus {
  const esHasContent = hasEditorHtmlContent(draft.content_html_es);
  const enHasContent = hasEditorHtmlContent(draft.content_html_en);

  return {
    es: {
      hasContent: esHasContent,
      label: esHasContent ? 'Con contenido' : 'Vacío',
      hasTitle: (draft.title_es || '').trim().length > 0,
    },
    en: {
      hasContent: enHasContent,
      label: enHasContent ? 'Con contenido' : 'Vacío',
      hasTitle: (draft.title_en || '').trim().length > 0,
    },
  };
}
